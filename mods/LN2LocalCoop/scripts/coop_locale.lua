function M.text(language,message,...)
 local catalog=languages[language]
 local translated=catalog and catalog[message] or message
 if select('#',...)>0 then return translated:format(...) end
 return translated
end

function M.notice(language,message)
 if not message or not languages[language] then return message end
 if message:match('^ayudante sin apoyo;') then return M.text(language,'El ayudante necesita suelo firme') end
 local saved=message:match('^Guardado: (.+)$')
 if saved then return M.text(language,'Guardado: %s',M.text(language,saved)) end
 local p2=message:match('^Ya usada para (.+) del jugador 2$')
 if p2 then return M.text(language,'Ya usada para %s del jugador 2',M.text(language,p2)) end
 local used=message:match('^Ya usada para (.+)$')
 if used then return M.text(language,'Ya usada para %s',M.text(language,used)) end
 local role=message:match('^Salto asistido de P([12])$')
 if role then return M.text(language,'Salto asistido de P%d',tonumber(role)) end
 return M.text(language,message)
end

return M
